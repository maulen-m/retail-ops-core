#!/usr/bin/env python3
"""Evaluate strict success gate for unattended Kaspi import runs."""

from __future__ import annotations

import argparse
import json
from datetime import date, datetime
from pathlib import Path
from typing import Any

import pandas as pd


def _coerce_int(value: Any, field_name: str) -> int:
    if value is None:
        raise ValueError(f"missing required field: {field_name}")
    try:
        return int(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"invalid integer for {field_name}: {value!r}") from exc


def _parse_target_date(raw: str) -> date:
    try:
        return datetime.strptime(raw, "%Y-%m-%d").date()
    except ValueError as exc:
        raise ValueError(f"invalid target date (expected YYYY-MM-DD): {raw}") from exc


def _normalize_order_ids(series: pd.Series) -> pd.Series:
    return (
        series.astype(str)
        .str.replace(r"\.0$", "", regex=True)
        .str.strip()
    )


def _date_series(df: pd.DataFrame, candidates: list[str]) -> pd.Series | None:
    for col in candidates:
        if col in df.columns:
            series = df[col]
            if pd.api.types.is_datetime64_any_dtype(series):
                return pd.to_datetime(series, errors="coerce").dt.date

            as_text = series.astype(str)
            has_dmy = as_text.str.match(r"^\s*\d{1,2}\.\d{1,2}\.\d{4}\s*$", na=False).any()
            if has_dmy:
                parsed_dmy = pd.to_datetime(series, errors="coerce", format="%d.%m.%Y")
                return parsed_dmy.dt.date

            parsed_ymd = pd.to_datetime(series, errors="coerce", format="%Y-%m-%d")
            return parsed_ymd.dt.date
    return None


def _collect_activeorders_ids(path: Path, target_date: date) -> set[str]:
    if not path.exists():
        raise ValueError(f"activeorders file not found: {path}")
    df = pd.read_excel(path)

    order_col = "№ заказа" if "№ заказа" in df.columns else ("OrderID" if "OrderID" in df.columns else None)
    if not order_col:
        raise ValueError("activeorders missing order id column (№ заказа/OrderID)")

    ids = _normalize_order_ids(df[order_col])
    dates = _date_series(df, ["Плановая дата передачи курьеру", "PLANNED_SHIPPING_DATE", "Date"])
    if dates is not None:
        ids = ids[dates == target_date]
    out = {v for v in ids.tolist() if v and v.lower() != "nan" and v.lower() != "none"}
    return out


def _collect_crm_ids(path: Path, sheet_name: str, target_date: date) -> set[str]:
    if not path.exists():
        raise ValueError(f"crm file not found: {path}")
    df = pd.read_excel(path, sheet_name=sheet_name)

    order_candidates = [col for col in ("OrderID", "№ заказа") if col in df.columns]
    if not order_candidates:
        raise ValueError("crm missing order id column (OrderID/№ заказа)")

    dates = _date_series(df, ["Date", "PLANNED_SHIPPING_DATE", "Плановая дата передачи курьеру"])
    if dates is None:
        raise ValueError("crm missing date column (Date/PLANNED_SHIPPING_DATE)")

    target_mask = dates == target_date
    best_ids: pd.Series | None = None
    best_count = -1
    for order_col in order_candidates:
        candidate_ids = _normalize_order_ids(df[order_col])[target_mask]
        valid_ids = candidate_ids[
            candidate_ids.astype(str).str.lower().ne("nan")
            & candidate_ids.astype(str).str.lower().ne("none")
            & candidate_ids.astype(str).str.strip().ne("")
        ]
        count = int(valid_ids.shape[0])
        if count > best_count:
            best_count = count
            best_ids = candidate_ids

    ids = best_ids if best_ids is not None else _normalize_order_ids(df[order_candidates[0]])[target_mask]
    out = {v for v in ids.tolist() if v and v.lower() != "nan" and v.lower() != "none"}
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description="Evaluate strict success gate for CRM import run")
    parser.add_argument("--step2-rc", type=int, required=True, help="Return code of Step 2 import subprocess")
    parser.add_argument("--health-json", type=Path, required=True, help="Path to JSON generated by report_import_status.py")
    parser.add_argument("--activeorders-file", type=Path, default=None, help="ActiveOrders snapshot used in this run")
    parser.add_argument("--crm-file", type=Path, default=None, help="CRM workbook path")
    parser.add_argument("--target-date", default=None, help="Target date YYYY-MM-DD for snapshot parity")
    parser.add_argument("--crm-sheet", default="SALES_KSP_CRM_1", help="CRM sheet name")
    args = parser.parse_args()

    if args.step2_rc != 0:
        print(f"HARD_FAIL: step2_rc={args.step2_rc}")
        return 1

    use_snapshot_gate = any(
        value is not None
        for value in (args.activeorders_file, args.crm_file, args.target_date)
    )
    snapshot_success_message: str | None = None
    if use_snapshot_gate:
        if not (args.activeorders_file and args.crm_file and args.target_date):
            print("HARD_FAIL: snapshot gate requires --activeorders-file, --crm-file, and --target-date")
            return 1
        try:
            target_date = _parse_target_date(args.target_date)
            active_ids = _collect_activeorders_ids(args.activeorders_file, target_date)
            crm_ids = _collect_crm_ids(args.crm_file, args.crm_sheet, target_date)
        except Exception as exc:
            print(f"HARD_FAIL: snapshot gate evaluation error: {exc}")
            return 1

        miss = sorted(active_ids - crm_ids)
        if miss:
            sample = ", ".join(miss[:5])
            print(
                "HARD_FAIL: activeorders snapshot mismatch "
                f"(target_date={target_date}, miss_count={len(miss)}, sample={sample})"
            )
            return 1

        snapshot_success_message = (
            "SUCCESS_GATE_OK: activeorders snapshot parity "
            f"(target_date={target_date}, orders={len(active_ids)})"
        )

    if not args.health_json.exists():
        print(f"HARD_FAIL: health json missing: {args.health_json}")
        return 1

    try:
        payload = json.loads(args.health_json.read_text(encoding="utf-8"))
    except Exception as exc:  # pragma: no cover - defensive path
        print(f"HARD_FAIL: cannot parse health json: {exc}")
        return 1

    totals = payload.get("totals", {})
    try:
        miss_crm = _coerce_int(totals.get("miss_crm"), "totals.miss_crm")
        stale_crm = _coerce_int(totals.get("stale_crm", 0), "totals.stale_crm")
        miss_seller_fee = _coerce_int(totals.get("miss_seller_fee", 0), "totals.miss_seller_fee")
        api_today = _coerce_int(totals.get("api_today"), "totals.api_today")
        crm_today = _coerce_int(totals.get("crm_today"), "totals.crm_today")
    except ValueError as exc:
        print(f"HARD_FAIL: {exc}")
        return 1

    if miss_crm > 0:
        print(f"HARD_FAIL: miss_crm={miss_crm} (api_today={api_today}, crm_today={crm_today})")
        return 1
    if stale_crm > 0:
        print(f"HARD_FAIL: stale_crm={stale_crm} (api_today={api_today}, crm_today={crm_today})")
        return 1
    if miss_seller_fee > 0:
        print(
            "HARD_FAIL: "
            f"miss_seller_fee={miss_seller_fee} (api_today={api_today}, crm_today={crm_today})"
        )
        return 1

    if snapshot_success_message:
        print(
            f"{snapshot_success_message} live_api_miss_crm=0 stale_crm=0 "
            "miss_seller_fee=0"
        )
    else:
        print(
            f"SUCCESS_GATE_OK: step2_rc=0 api_today={api_today} "
            f"crm_today={crm_today} miss_crm=0 stale_crm=0 miss_seller_fee=0"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
